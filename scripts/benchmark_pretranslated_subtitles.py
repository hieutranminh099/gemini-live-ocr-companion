"""100 real Android source transitions using Gemini-pretranslated public text.

Requires docs/results/subtitle-prewarm-live-v163.json, active OCR, unchanged ROI
and the native TestScene APK. Does not auto-run cloud inference or change settings.
This measures cache playback, never fresh Gemini latency or translation quality.
"""
import argparse
import json
from pathlib import Path
import shlex
import time

from benchmark_subtitle_pipeline import Benchmark, SCENE, percentiles, source_hash

ROOT = Path(__file__).resolve().parents[1]


def execute(bench, samples, *, count=100, cue_ms=800, report_path=None, android_version='1.6.3'):
    before = bench.status()
    ident = f'pretranslated-{bench.started_ms}'
    sequence = [dict(id=f'{ident}-{i}', text=samples[i % len(samples)]['source'], durationMs=cue_ms) for i in range(count)]
    left, top, right, bottom = bench.args.roi
    bench.run('shell', 'am', 'start', '-f', '0x20000000', '-n', SCENE,
              '--ez', 'subtitle', 'true', '--ez', 'animate', 'true',
              '--ef', 'sourceCenter', str(((left+right)/2)/bench.args.width),
              '--ef', 'subtitleBaseline', str((top+.78*(bottom-top))/bench.args.height),
              '--ef', 'subtitleSp', str(bench.args.subtitle_sp),
              '--es', 'sequenceJson', shlex.quote(json.dumps(sequence, ensure_ascii=False)))
    first = bench.wait(lambda e: e.get('event') == 'source_drawn' and e.get('id') == sequence[0]['id'], 8)
    target_end = first['at_ms'] + count * cue_ms + 1000
    # Read regularly to retain events even on a small Android logcat ring.
    collected = {}
    deadline = time.monotonic() + count * cue_ms / 1000 + 15
    while time.monotonic() < deadline:
        for event in bench.events():
            collected[json.dumps(event, sort_keys=True)] = event
        uptime = int(float(bench.run('shell','cat','/proc/uptime').decode().split()[0])*1000)
        if uptime >= target_end:
            break
        time.sleep(2)
    events = sorted(collected.values(), key=lambda e:e['at_ms'])
    sources = [e for e in events if e.get('event') == 'source_drawn' and str(e.get('id','')).startswith(ident)]
    overlays = [e for e in events if e.get('event') == 'overlay_drawn' and e['at_ms'] >= first['at_ms']]
    rows, stale = [], []
    for index, source in enumerate(sources):
        cue_index = int(source['id'].rsplit('-',1)[1])
        expected = samples[cue_index % len(samples)]
        end = sources[index+1]['at_ms'] if index+1 < len(sources) else source['at_ms'] + cue_ms
        draws = [e for e in overlays if source['at_ms'] <= e['at_ms'] < end]
        valid = [e for e in draws if e.get('source_hash') == source_hash(expected['source']) and
                 e.get('translation_hash') == expected['translation_hash']]
        stale += [e for e in draws if e not in valid]
        draw = valid[0] if valid else None
        rows.append(dict(cue=cue_index, source_hash=source_hash(expected['source']), matched=draw is not None,
                         source_to_overlay_ms=draw['at_ms']-source['at_ms'] if draw else None,
                         phone_cache=draw.get('phone_cache') if draw else None, overlay=draw))
    after = bench.status()
    out = dict(measurement='Android source first draw to overlay draw, Gemini-pretranslated cache only',
               android_version=android_version, windows_version=after['version'], roi=bench.args.roi,
               expected_cues=count, observed_source_cues=len(sources), cue_duration_ms=cue_ms,
               matched_cues=sum(row['matched'] for row in rows), missed_cues=sum(not row['matched'] for row in rows),
               stale_or_wrong_translation_draws=stale, new_ai_calls=after['usage']['requests']-before['usage']['requests'],
               new_server_errors=after['metrics']['errors']-before['metrics']['errors'],
               phone_cache_draws=sum(row['phone_cache'] is True for row in rows),
               server_cache_draws=sum(row['phone_cache'] is False for row in rows),
               latency_ms=percentiles([row['source_to_overlay_ms'] for row in rows if row['matched']]),
               samples=rows, events=events,
               limitations=[f'{count} transitions repeat three exact public source sentences.',
                            'Cache was generated by one Gemini batch before playback; these are not 100 fresh AI inferences.',
                            'No claim for an unseen movie, OCR errors, different font/ROI/network or Redmi hardware.',
                            'Canvas draw timestamp, not GPU presentation time; missed cues counted separately.'])
    out['passed'] = len(sources)==count and out['matched_cues']==count and not stale and out['new_ai_calls']==0
    path=ROOT/(report_path or 'docs/results/pretranslated-android-100-v163.json')
    path.write_text(json.dumps(out,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    bench.screenshot('cache-100')
    print(json.dumps({k:v for k,v in out.items() if k not in ('samples','events')},ensure_ascii=False),flush=True)
    return out


def main():
    data=json.loads((ROOT/'docs/results/subtitle-prewarm-live-v163.json').read_text(encoding='utf-8'))
    assert data['status']=='passed'
    args=argparse.Namespace(serial='127.0.0.1:5555',phase='pretranslated-v163',roi=[233,496,809,538],width=1600,height=900,
                            subtitle_sp=24,timeout=10,resume=None)
    bench=Benchmark(args)
    try:
        result=execute(bench,data['samples'])
        assert result['passed'], 'See saved report: missing/stale draws or unexpected AI calls'
    finally:
        bench.client.close()


if __name__=='__main__':
    main()
